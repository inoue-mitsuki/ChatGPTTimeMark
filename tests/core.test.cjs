test('分割されたCRLFストリームと複数行dataを処理する', () => {
  const output = [];
  const feed = core.streamParser(records => output.push(...records));
  const raw = `data: ${JSON.stringify({ type: 'input_message', input_message: message })}\r\n\r\n`;
  for (const char of raw) feed(char);
  feed('data: [DONE]\n\ndata: invalid\n\n');
  feed(`data: {"v":\ndata: ${JSON.stringify({ message })}}\n\n`);
  assert.deepEqual(output, [{ id: 'user-1', seconds }, { id: 'user-1', seconds }]);
});
