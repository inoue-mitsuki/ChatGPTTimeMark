test('表示処理は重複・ID変更・会話切替・他サイト由来の通知を扱う', () => {
  // Minimal DOM fixture: tests behavior without claiming a real-browser result.
  let handler;
  let mutate;
  const tasks = [];
  const location = { pathname: '/c/first', origin: 'https://chatgpt.com' };
  const user = {
    id: 'user-1', role: 'user', children: [],
    carrier: null,
    getAttribute(name) { return name === 'data-chatgpt-timestamp-record' ? this.carrier : this.id; },
    matches() { return this.role === 'user'; },
    querySelector() { return this.children[0] || null; },
    prepend(stamp) { this.children.unshift(stamp); stamp.parentElement = this; }
  };
  const document = {
    querySelectorAll(selector) { return selector.startsWith('time') ? [...user.children] : user.role === 'user' ? [user] : []; },
    createElement() { return { textContent: '', dateTime: '', setAttribute() {}, remove() { user.children = user.children.filter(x => x !== this); } }; }
  };
  const window = { addEventListener(type, listener) { if (type === 'message') handler = listener; }, postMessage() {} };
  vm.runInNewContext(fs.readFileSync('src/content.js', 'utf8'), {
    window, document, location, ChatGPTTimeMarkCore: core,
    setTimeout(fn) { tasks.push(fn); },
    MutationObserver: class { constructor(callback) { mutate = callback; } observe() {} }
  });
  const flush = () => { while (tasks.length) tasks.shift()(); };
  const notify = (records, route = location.pathname, origin = location.origin) => handler({ source: window, origin, data: { type: 'CHATGPT_TIMESTAMP_V1', route, records } });
  flush();
  assert.equal(user.children.length, 0);
  user.carrier = JSON.stringify({ id: user.id, seconds, route: location.pathname });
  mutate(); flush();
  assert.equal(user.children.length, 1);
  assert.equal(user.children[0].textContent, core.format(seconds));
  user.carrier = JSON.stringify({ id: user.id, seconds, firstSeconds: seconds - 60, versionCount: 2, route: location.pathname });
  mutate(); flush();
  assert.equal(user.children[0].textContent, core.format(seconds));
  user.carrier = JSON.stringify({ id: 'different-user', seconds, route: location.pathname });
  mutate(); flush();
  assert.equal(user.children.length, 0);
  user.carrier = JSON.stringify({ id: user.id, seconds, route: '/c/stale' });
  mutate(); flush();
  assert.equal(user.children.length, 0);
  user.carrier = null;
  notify([{ id: user.id, seconds }], location.pathname, 'https://example.com'); flush();
  assert.equal(user.children.length, 0);
  notify([{ id: user.id, seconds }]); flush();
  assert.equal(user.children.length, 1);
  assert.equal(user.children[0].textContent, core.format(seconds));
  notify([{ id: user.id, seconds }]); mutate(); flush();
  assert.equal(user.children.length, 1);
  user.id = 'edited-user'; mutate(); flush();
  assert.equal(user.children.length, 0);
  notify([{ id: user.id, seconds }]); flush();
  user.role = 'assistant'; mutate(); flush();
  assert.equal(user.children.length, 0);
  user.role = 'user';
  location.pathname = '/c/second'; mutate(); flush();
  assert.equal(user.children.length, 0);
  notify([{ id: user.id, seconds }], '/c/first'); flush();
  assert.equal(user.children.length, 0);
});

