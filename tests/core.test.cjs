test('React取得は現在のツリーでIDが一致する投稿だけを返す', () => {
  const state = {};
  const root = { tag: 3, stateNode: state };
  state.current = root;
  const staleRoot = { tag: 3, stateNode: state };
  const current = { memoizedProps: { messages: [message] }, return: root };
  root.child = current;
  const stale = { memoizedProps: { messages: [{ ...message, create_time: seconds - 60 }] }, return: staleRoot, alternate: current };
  const element = { matches: () => true, getAttribute: () => message.id, '__reactFiber$test': stale };
  assert.deepEqual(core.reactRecord(element), { id: message.id, seconds });
  element.getAttribute = () => 'different';
  assert.equal(core.reactRecord(element), null);
  element.getAttribute = () => message.id;
  current.memoizedProps.messages = [{ ...message, author: { role: 'assistant' } }];
  assert.equal(core.reactRecord(element), null);
  current.return = current;
  assert.equal(core.reactRecord(element), null);
});

test('現行React構造は会話と表示ターンが一致するスナップショットから取得する', () => {
  const turn = { items: [{ type: 'user-message', messageId: message.id }] };
  const entry = { id: 'turn-1', conversationId: 'conversation-1', turn };
  const snapshot = { renderedConversation: { mapping: { [message.id]: { id: message.id, message } } }, renderedTurns: [entry] };
  const root = { tag: 3, stateNode: {} };
  root.stateNode.current = root;
  const owner = { memoizedProps: { conversationId: entry.conversationId }, memoizedState: { memoizedState: [snapshot] }, return: root };
  const row = { memoizedProps: { entry }, return: owner };
  root.child = owner; owner.child = row;
  const element = { matches: () => true, getAttribute: () => message.id, '__reactFiber$new': row };
  assert.deepEqual(core.reactRecord(element, entry.conversationId), { id: message.id, seconds });
  assert.equal(core.reactRecord(element, 'different-conversation'), null);
  snapshot.renderedTurns = [{ ...entry, turn: { ...turn } }];
  assert.equal(core.reactRecord(element, entry.conversationId), null);
  snapshot.renderedTurns = [entry];
  owner.memoizedState.next = { memoizedState: { ...snapshot, renderedConversation: { mapping: { [message.id]: { id: message.id, message: { ...message, create_time: seconds - 1 } } } } } };
  assert.equal(core.reactRecord(element, entry.conversationId), null);
  owner.memoizedState.next = null;
  owner.memoizedState.memoizedState = null;
  owner.updateQueue = { memoCache: { data: [[snapshot]] } };
  assert.deepEqual(core.reactRecord(element, entry.conversationId), { id: message.id, seconds });
});

